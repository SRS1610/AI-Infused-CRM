export function menuIcon(menu: { icon?: string | null; action?: string | null }): string {
  if (menu.icon && menu.icon in ICONS) return menu.icon;
  const action = menu.action ?? "";
  for (const [pattern, icon] of BY_ACTION) if (pattern.test(action)) return icon;
  return action ? "wrench" : "circle";
}

/** Two-letter initials for an avatar. */
export function initials(name: string | undefined | null): string {
  const parts = (name ?? "").trim().split(/\s+/).filter(Boolean);
  if (!parts.length) return "?";
  return (parts.length === 1 ? parts[0].slice(0, 2) : parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
}
