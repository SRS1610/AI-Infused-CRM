"""AI commands: evaluations, completeness report, compliance classification, retrieval index."""

from __future__ import annotations

import json
from pathlib import Path

import typer
from rich.console import Console
from rich.table import Table

app = typer.Typer(no_args_is_help=True)
eval_app = typer.Typer(no_args_is_help=True)
app.add_typer(eval_app, name="eval", help="Evaluation sets: run (replay | record | live) and report")
console = Console()


def _url(database_url: str | None) -> str:
    from tessera.config import get_settings

    return database_url or get_settings().database_url


@eval_app.command("run")
def eval_run(
    features: list[str] = typer.Argument(None, help="Feature names (default: every declared feature)"),
    mode: str = typer.Option("replay", "--mode", help="replay (CI), record (refresh cassettes) or live (nightly)"),
    module: list[str] = typer.Option(None, "--module", help="Only features of these modules"),
    save: bool = typer.Option(False, "--save", help="Store the result as ai_core.eval_run"),
    output: Path | None = typer.Option(None, "--json", help="Write the reports as JSON"),
    database_url: str | None = typer.Option(None, "--database-url"),
) -> None:
    """Run evaluation sets; exits non-zero when a threshold is not met."""
    from tessera.ai import evals
    from tessera.orm.environment import environment_for

    if mode not in ("replay", "record", "live"):
        raise typer.BadParameter("mode must be replay, record or live")
    specs = evals.feature_specs(features or None, module or None)
    reports = []
    with environment_for(_url(database_url), su=True) as env:
        for spec in specs:
            with env.cr.savepoint():
                report = evals.evaluate(env, spec, mode=mode)
            reports.append(report)
            if save:
                evals.save_report(env, report)
    table = Table("feature", "prompt", "cases", "metrics", "result")
    for r in reports:
        table.add_row(
            r.feature,
            r.prompt_version,
            str(r.cases),
            ", ".join(f"{k}={v}" for k, v in r.metrics.items()),
            "[green]pass[/]" if r.passed else "[red]" + "; ".join(r.failures) + "[/]",
        )
    console.print(table)
    if output:
        output.write_text(json.dumps([evals.summary(r) for r in reports], indent=2))
    if any(not r.passed for r in reports):
        raise typer.Exit(1)


@eval_app.command("report")
def eval_report(
    strict: bool = typer.Option(False, "--strict", help="Exit non-zero when anything is missing"),
    module: list[str] = typer.Option(None, "--module"),
) -> None:
    """What each declared AI feature still lacks: prompt, flag, thresholds, eval cases, cassettes, guardrail cases."""
    from tessera.ai import evals

    missing = evals.completeness(evals.feature_specs(modules=module or None))
    for line in missing:
        console.print(f"[red]missing[/] {line}")
    if not missing:
        console.print("[green]every declared AI feature is complete[/]")
    if strict and missing:
        raise typer.Exit(1)


@app.command("classification")
def classification(output: Path = typer.Option(Path("../docs/ai-governance/CLASSIFICATION.md"), "--output")) -> None:
    """Generate the compliance classification table from the feature manifests (so it cannot drift)."""
    from tessera.ai import evals

    specs = sorted(evals.feature_specs(), key=lambda s: (s.module, s.name))
    lines = [
        "# AI feature classification",
        "",
        "Generated by `tessera ai classification` from every module's `ai/features.yaml`. Do not edit by hand.",
        "",
        "| Feature | Module | Task class | Risk class | Employment | Writes | Outbound | Human decision | Bias tests |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for s in specs:
        if s.module.endswith("_test"):
            continue
        f = s.data
        cells = [
            f"`{f['name']}` — {f.get('title', '')}",
            s.module,
            f["task_class"],
            f.get("risk_class", "minimal"),
            "yes" if f.get("employment_related") else "no",
            "proposal" if f.get("writes") else "no",
            "proposal" if f.get("outbound") else "no",
            "required" if f.get("human_decision") else "—",
            f.get("bias_tests") or "—",
        ]
        lines.append("| " + " | ".join(cells) + " |")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n")
    console.print(f"wrote {output} ({len(lines) - 6} features)")


@app.command("reindex")
def reindex(
    models: list[str] = typer.Argument(None, help="Models to re-index (default: every model with _ai_index)"),
    database_url: str | None = typer.Option(None, "--database-url"),
) -> None:
    """Rebuild the retrieval index now (in this process)."""
    from tessera.ai import retrieval
    from tessera.orm.environment import environment_for

    with environment_for(_url(database_url), su=True) as env:
        counts = retrieval.rebuild(env, models or None)
    for model, n in counts.items():
        console.print(f"{model}: {n} chunks")
